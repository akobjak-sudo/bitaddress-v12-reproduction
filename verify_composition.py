#!/usr/bin/env python3
"""
Independent reproduction of the bitaddress.org v1.2 entropy failure
under Firefox 6, verified against a live browser capture.

Usage: python3 verify_composition.py
Requires: Python 3 standard library only. Reads capture/*.json.

This script contains no address-search logic. It analyses one capture
of a wallet generated by the researcher in a controlled session.
"""
import hashlib, json, os, sys

CAP = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                   "capture", "ff6_win7_bitaddress_v12.json")

M48  = (1 << 48) - 1
MUL  = 0x5DEECE66D
ADD  = 0xB
INV  = pow(MUL, -1, 1 << 48)
NSEC = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEBAAEDCE6AF48A03BBFD25E8CD0364141
P256 = 2**256 - 2**32 - 977
Gx   = 0x79BE667EF9DCBBAC55A06295CE870B07029BFCDB2DCE28D959F2815B16F81798
Gy   = 0x483ADA7726A3C4655DA4FBFC0E1108A8FD17B448A68554199C47D08FFB10D4B8
AL   = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz"


def stream(seed48, n):
    """SpiderMonkey FF6 Math.random: two LCG steps per output."""
    st = (seed48 ^ MUL) & M48
    out = []
    for _ in range(n):
        st = (st * MUL + ADD) & M48; a = st >> 22
        st = (st * MUL + ADD) & M48; b = st >> 21
        out.append(((a << 27) + b) / (1 << 53))
    return out


def recover(mr):
    """Recover seed48 = ms ^ P from logged outputs. Returns None if not LCG-48."""
    N  = [round(v * 2**53) for v in mr]
    hi = [n >> 27 for n in N]
    lo = [n & ((1 << 27) - 1) for n in N]
    base = lo[0] << 21
    for s2 in range(base, base + (1 << 21)):
        s1 = ((s2 - ADD) * INV) & M48
        if (s1 >> 22) != hi[0]:
            continue
        cur = s2                      # state AFTER lo[0], not s1
        ok = True
        for i in range(1, len(mr)):
            cur = (cur * MUL + ADD) & M48
            if (cur >> 22) != hi[i]: ok = False; break
            cur = (cur * MUL + ADD) & M48
            if (cur >> 21) != lo[i]: ok = False; break
        if ok:
            s0 = ((s1 - ADD) * INV) & M48
            return (s0 ^ MUL) & M48
    return None


def pool_base(vals):
    """128 calls x 2 bytes = 256-byte pool, before XOR."""
    p = bytearray(256)
    for i in range(128):
        t = int(65536.0 * vals[i]) & 0xFFFF
        p[2*i] = (t >> 8) & 0xFF
        p[2*i+1] = t & 0xFF
    return p


def xor_le(p, off, val):
    v = val & 0xFFFFFFFF
    for i, sh in enumerate((0, 8, 16, 24)):
        p[off+i] ^= (v >> sh) & 0xFF


def priv_from_pool(p):
    S = list(range(256)); j = 0
    for i in range(256):
        j = (j + S[i] + p[i]) & 0xFF
        S[i], S[j] = S[j], S[i]
    i = j = 0; rb = bytearray()
    for _ in range(33):
        i = (i + 1) & 0xFF; j = (j + S[i]) & 0xFF
        S[i], S[j] = S[j], S[i]
        rb.append(S[(S[i] + S[j]) & 0xFF])
    raw = int.from_bytes(bytes(rb[1:33]), 'big')
    return ((raw % (NSEC - 1)) + 1).to_bytes(32, 'big')


def padd(A, B):
    if A is None: return B
    if B is None: return A
    if A[0] == B[0] and (A[1] + B[1]) % P256 == 0: return None
    l = ((3*A[0]*A[0]) * pow(2*A[1], -1, P256) % P256 if A == B
         else (B[1]-A[1]) * pow(B[0]-A[0], -1, P256) % P256)
    x = (l*l - A[0] - B[0]) % P256
    return (x, (l*(A[0]-x) - A[1]) % P256)


def addr_from_priv(k):
    R = None; G = (Gx, Gy); s = int.from_bytes(k, 'big')
    while s:
        if s & 1: R = padd(R, G)
        G = padd(G, G); s >>= 1
    x = R[0].to_bytes(32, 'big'); y = R[1].to_bytes(32, 'big')
    h = hashlib.new('ripemd160', hashlib.sha256(b'\x04'+x+y).digest()).digest()
    pl = b'\x00' + h
    full = pl + hashlib.sha256(hashlib.sha256(pl).digest()).digest()[:4]
    n = int.from_bytes(full, 'big'); out = ""
    while n:
        n, r = divmod(n, 58); out = AL[r] + out
    for c in full:
        if c == 0: out = "1" + out
        else: break
    return out


def main():
    d = json.load(open(CAP, encoding="utf-8"))
    mr, pool = d["mr"], d["pool"]

    print("=" * 68)
    print("bitaddress v1.2 / Firefox 6 — composition verification")
    print("=" * 68)

    print("\n[0] Capture gate")
    gate = [("ua contains rv:6.0", "rv:6.0" in d["ua"]),
            ("hasCrypto is false", d["hasCrypto"] is False),
            ("len(mr) == 140",     len(mr) == 140),
            ("len(pool) == 256",   len(pool) == 256),
            ("len(st) == 3",       len(d["st"]) == 3)]
    for name, ok in gate:
        print(f"    {name}: {'OK' if ok else 'FAIL'}")
    if not all(o for _, o in gate):
        print("\nGATE FAIL — capture is not Firefox 6. Nothing below is meaningful.")
        return 1

    print("\n[1] LCG-48 state recovery")
    seed48 = recover(mr)
    if seed48 is None:
        print("    FAIL: stream is not LCG-48")
        return 1
    print(f"    seed48 = ms ^ P = {seed48} ({hex(seed48)})")
    regen = stream(seed48, 140)
    stream_ok = all(a == b for a, b in zip(regen, mr))
    print(f"    stream 140/140: {'OK' if stream_ok else 'FAIL'}")

    print("\n[2] Timestamps from XOR mask")
    base = pool_base(mr)                       # from logged mr, independent of LCG
    mask = bytes(pool[i] ^ base[i] for i in range(256))
    ta   = d["t_after_sr"]
    hi32 = ta - (ta & 0xFFFFFFFF)
    Ti   = hi32 + int.from_bytes(mask[0:4],   'little')
    fg   = hi32 + int.from_bytes(mask[12:16], 'little')
    sdT  = hi32 + int.from_bytes(mask[16:20], 'little')
    genT = hi32 + int.from_bytes(mask[20:24], 'little')
    print(f"    T_init = {Ti}   (t_after_sr = {ta}, delta = {Ti-ta} ms)")
    print(f"    T_fg   = {fg}   T_seed = {sdT}   T_gen = {genT}")
    print(f"    screenX = {d['sx']}  screenY = {d['sy']}")
    sl = 50 + int(256.0 * mr[139])
    print(f"    seedLimit = {sl}  timeout = {sl*20} ms  jitter = {fg-Ti-sl*20} ms")

    print("\n[3] Pool reconstruction")
    p = pool_base(regen)
    xor_le(p, 0, Ti); xor_le(p, 4, d["sx"]); xor_le(p, 8, d["sy"])
    xor_le(p, 12, fg); xor_le(p, 16, sdT); xor_le(p, 20, genT)
    same = sum(1 for i in range(256) if p[i] == pool[i])
    print(f"    pool match: {same}/256")

    print("\n[4] Key derivation")
    k = priv_from_pool(p)
    key_ok = k.hex() == priv_from_pool(bytearray(pool)).hex()
    print(f"    from reconstructed pool: {k.hex()}")
    print(f"    from captured pool:      {priv_from_pool(bytearray(pool)).hex()}")
    print(f"    key: {'PASS' if key_ok else 'FAIL'}")

    print("\n[5] Address derivation")
    a = addr_from_priv(k)
    addr_ok = (a == d["addr"])
    print(f"    got:      {a}")
    print(f"    captured: {d['addr']}")
    print(f"    addr: {'PASS' if addr_ok else 'FAIL'}")

    res = [("capture gate", all(o for _, o in gate)),
           ("stream 140/140", stream_ok),
           ("pool 256/256", same == 256),
           ("key", key_ok),
           ("address", addr_ok)]
    print("\n" + "=" * 68)
    for n, o in res:
        print(f"  {n}: {'PASS' if o else 'FAIL'}")
    all_ok = all(o for _, o in res)
    print(f"RESULT: {'COMPOSITION PASS' if all_ok else 'COMPOSITION FAIL'}")
    print("=" * 68)
    return 0 if all_ok else 1


if __name__ == "__main__":
    sys.exit(main())